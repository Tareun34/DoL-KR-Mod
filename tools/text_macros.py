#!/usr/bin/env python3
"""Derive the list of "text macros" from the translation records.

    text_macros.py --root . [--min-records 2] --out translation/text-macros.txt

A text macro is an argument-less widget that prints a pronoun or noun
(<<he>>, <<person1>>, <<girl>>...). Korean sentences legitimately drop or
move them, so check_translation.py ignores them when comparing structure.
The list is derived from evidence: names whose count differs between the
old English and the old Korean of the same conflict record.
"""
import argparse
import collections
import glob
import json
import os
import re
import sys

try:
    from tools.translation_status import has_prose
except ImportError:
    from translation_status import has_prose

ARGLESS_MACRO_RE = re.compile(r"<<([A-Za-z_][\w]*)>>")
DENY = {"else", "default", "break", "continue", "endevent", "exitall", "runeventpool", "cleareventpool",
        "stateman", "actionsman", "nexttext", "silently", "nobr"}


def candidates(root, min_records=2):
    """[(name, records where count differs, records where seen)] sorted by differing count desc."""
    diff, seen = collections.Counter(), collections.Counter()
    for path in glob.glob(os.path.join(root, "translation", "pending", "**", "*.twee.json"), recursive=True):
        with open(path, encoding="utf-8") as f:
            records = json.load(f)
        for r in records:
            if r.get("kind") != "conflict" or not r.get("old_kr") or not has_prose(r.get("old_en", [])):
                continue
            ce = collections.Counter(m.lower() for l in r["old_en"] for m in ARGLESS_MACRO_RE.findall(l))
            ck = collections.Counter(m.lower() for l in r["old_kr"] for m in ARGLESS_MACRO_RE.findall(l))
            for name in set(ce) | set(ck):
                seen[name] += 1
                if ce[name] != ck[name]:
                    diff[name] += 1
    out = [(n, diff[n], seen[n]) for n in diff if diff[n] >= min_records and n not in DENY]
    return sorted(out, key=lambda x: (-x[1], x[0]))


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--root", default=".")
    parser.add_argument("--min-records", type=int, default=2)
    parser.add_argument("--out", required=True)
    args = parser.parse_args(argv)
    rows = candidates(args.root, args.min_records)
    with open(args.out, "w", encoding="utf-8") as f:
        f.write("# generated by tools/text_macros.py; name  # differing/seen\n")
        for name, d, s in rows:
            f.write("%s  # %d/%d\n" % (name, d, s))
    print("wrote %s (%d names)" % (args.out, len(rows)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
